"""Additional synthetic truth families. NumPy only; no estimator imports."""
import numpy as np
from independent_plant import IndependentPlant

class LocalizedPlant(IndependentPlant):
    """Two broad harmonics plus smooth localized periodic runout.

    The localized term is analytic, not a spline generated by the estimator.
    Its infinite harmonic expansion prevents exact preference for either tested
    finite Fourier or cubic-spline family. Datum zero and scale remain separate.
    """
    def __init__(self,seed=831,**kwargs):
        super().__init__(seed,**kwargs)
        rng=np.random.default_rng(seed+47000)
        self.centres=rng.uniform(.4,5.8,6)
        self.amplitudes=rng.normal(size=6)*np.array([.009]*3+[14e-6]*3)
        self.concentration=rng.uniform(3,6,6)
    def errors(self,q):
        e=super().errors(q);c=q[4]
        selfpart=self.c_coeff[:,:4]@np.array([np.sin(c),np.cos(c)-1,np.sin(2*c),np.cos(2*c)-1])
        bump=np.exp(self.concentration*(np.cos(c-self.centres)-1))
        datum=np.exp(self.concentration*(np.cos(self.centres)-1))
        e[4]=selfpart+self.amplitudes*(bump-datum);e[4,5]+=self.c_scale*c
        return e

class MatchedPlant(IndependentPlant):
    """Exact nonlinear control with cubic XYZ/A and two C harmonics."""
    def __init__(self,seed=831,**kwargs):
        super().__init__(seed,mismatch=0.,**kwargs)
    def errors(self,q):
        e=super().errors(q)
        for j in range(3):
            u=q[j]/200;e[j]=self.linear[j]@np.array([u,u*u,u**3])
        return e
